# VARIABLE SIZE SLIDING WINDOW
# unlike a fixed- size window , a variable size window growa or shrinks depnding on a condition.

# example : find the length of the shortest subarray whose sum is at least 7 , given positive numbers



def min_subarray_length(numbers,target):
    left=0
    window_sum=0
    minimum=float("inf")

    for right in range(len(numbers)):
        window_sum+=numbers[right]
        while window_sum>=target:
            minimum=min(minimum,right-left+1)
            window_sum-=numbers[left]
            left+=1
    return 0 if minimum==float("inf") else minimum
print(min_subarray_length([2,3,1,2,4,3],7))

# ouput:
# 2

# time complexity   O(n)


# two pointer technique
# two pointer use two positions to traversw an array or string, often avoiding nested loops

# example : check wherher a sorted array contains two numbers whose sum equals the target.


def two_sum_sorted(numbers, target):
    left=0
    right=len(numbers)-1

    while left< right:
        total= numbers[left]+numbers[right]
        if total==target:
            return [left , right]
        elif total<target:
            left+=1
        else:
            right-=1
    return []
print(two_sum_sorted([1,2,4,6,8],10))

# output:
[1, 4]




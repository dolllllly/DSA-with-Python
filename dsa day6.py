# leetcode Move Zeroes — 283
# Move all zeroes to the end while preserving the order of nonzero elements.

def moveZero(nums):
    pointer=0
    for i in range(len(nums)):
        if nums[i]!=0:
            nums[pointer],nums[i]=nums[i],nums[pointer]
            pointer+=1
    return nums
print(moveZero([0,1,0,3,12]))

# output:
[1, 3, 12, 0, 0]




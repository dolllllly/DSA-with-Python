# Find two numbers summing to 12 in the sorted array [1, 3, 5, 7, 9]. Return their indices.

def twosumming_target(numbers, target):
    left=0
    right=len(numbers)-1
    while left<right:
        sum=numbers[left] + numbers[right]
        if sum ==target:
            return [left ,  right]
        elif sum<target:
            left+=1
        else:
            right-=1
    return []

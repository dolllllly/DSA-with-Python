# fixed size sliding window revision
# find the maximum sum of any 3 consecutive elements

def max_sum(numbers, k):
    window_sum=sum(numbers[:k])
    maximum= window_sum
    for right in range(k,len(numbers)):
        window_sum+=numbers[right]
        window_sum-=numbers[right-k]
        maximum=max(maximum,window_sum)
    return maximum
print(max_sum([2,1,5,1,3,2],3))

# ouptut:
# 9

# time complexity: O(n)
# space:  O(1

